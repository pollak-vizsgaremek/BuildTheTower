import { test, expect } from '@playwright/test';

test('project workspace, filters, views, database persistence and milestones', async ({ page, request }, testInfo) => {
  const suffix = `${testInfo.project.name}_${Date.now()}`;
  const registration = await request.post('/api/v1/auth/register', { data: { username: `pr_${suffix}`, email: `pr_${suffix}@example.test`, password: 'TestPassword123!', passwordConfirmation: 'TestPassword123!', acceptPrivacy: true } });
  expect(registration.status()).toBe(201);
  const cookies = await request.storageState();
  await page.context().addCookies(cookies.cookies);
  if (testInfo.project.name === 'desktop') await page.setViewportSize({ width: 1280, height: 720 });
  await page.goto('/Projektek');
  await expect(page.getByRole('heading', { name: 'Projektek & Kivitelezési Ütemterv' })).toBeVisible();
  await page.getByRole('button', { name: 'Mintaadatok betöltése', exact: true }).click();
  await expect(page.getByRole('article')).toHaveCount(3);
  await expect(page.getByRole('button', { name: /4 Aktív kivitelezés/ })).toBeVisible();
  await page.getByRole('button', { name: 'Értesítés bezárása', exact: true }).click();
  await page.screenshot({ path: `test-results/${testInfo.project.name}-projects.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Kártya nézet', exact: true }).click();
  await expect(page.getByRole('article')).toHaveCount(7);
  await page.getByLabel('Projekt keresése', { exact: true }).fill('Vaci');
  await expect(page.getByRole('article')).toHaveCount(1);
  await expect(page.getByRole('article')).toContainText('Váci Greens');
  await page.getByRole('button', { name: 'Keresés törlése' }).click();
  await page.getByLabel('Projekt státusza', { exact: true }).selectOption('preparation');
  await expect(page.getByRole('article')).toHaveCount(2);
  await page.getByLabel('Projekt státusza', { exact: true }).selectOption('all');
  await page.getByRole('button', { name: 'Táblázat nézet', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Projektek táblázata', exact: true }).getByRole('row')).toHaveCount(8);
  await page.getByRole('button', { name: 'További szűrők' }).click();
  await page.getByRole('combobox', { name: 'Haladás', exact: true }).selectOption('critical');
  await expect(page.getByRole('region', { name: 'Projektek táblázata', exact: true }).getByRole('row')).toHaveCount(2);
  await page.getByRole('button', { name: 'Szűrők törlése', exact: true }).click();
  await page.getByRole('button', { name: 'Új projekt indítása', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Projekt neve', { exact: true }).fill(`Teszt építkezés ${suffix}`);
  await dialog.getByLabel('Projektkód', { exact: true }).fill(`TEST-${Date.now()}`);
  await dialog.getByLabel('Helyszín', { exact: true }).fill('Budapest, Teszt utca 12.');
  await dialog.getByRole('combobox', { name: 'Státusz', exact: true }).selectOption('active');
  await dialog.getByLabel('Költségkeret (millió Ft)', { exact: true }).fill('120');
  await dialog.getByLabel('Felhasznált keret (millió Ft)', { exact: true }).fill('36');
  await dialog.getByLabel('Előrehaladás (%)', { exact: true }).fill('30');
  await dialog.getByLabel('Helyszíni létszám (fő)', { exact: true }).fill('16');
  await dialog.getByRole('button', { name: 'Projekt mentése' }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByLabel('Projekt keresése', { exact: true }).fill(`Teszt építkezés ${suffix}`);
  await page.getByRole('button', { name: `Teszt építkezés ${suffix} megtekintése`, exact: true }).click();
  await expect(dialog).toContainText('120 M Ft');
  await dialog.getByRole('button', { name: 'Projekt szerkesztése', exact: true }).click();
  await dialog.getByLabel('Előrehaladás (%)', { exact: true }).fill('42');
  await dialog.getByRole('button', { name: 'Projekt mentése' }).click();
  await expect(dialog).not.toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Kártya nézet', exact: true }).click();
  await page.getByLabel('Projekt keresése', { exact: true }).fill(`Teszt építkezés ${suffix}`);
  await expect(page.getByRole('article')).toContainText('42%');
  await page.getByRole('button', { name: `Teszt építkezés ${suffix} megtekintése`, exact: true }).click();
  await dialog.getByRole('button', { name: 'Új mérföldkő', exact: true }).click();
  await dialog.getByLabel('Mérföldkő / tevékenység', { exact: true }).fill('Alapozás ellenőrzése');
  await dialog.getByLabel('Felelős / alvállalkozó', { exact: true }).fill('Teszt Építő Kft.');
  await dialog.getByLabel('Feljegyzés / jegyzőkönyv szövege', { exact: true }).fill('Helyszíni ellenőrzés megtörtént.');
  await dialog.getByRole('button', { name: 'Mérföldkő mentése', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'Alapozás ellenőrzése részletei', exact: true }).click();
  await expect(dialog.getByLabel('Feljegyzés / jegyzőkönyv szövege', { exact: true })).toHaveValue('Helyszíni ellenőrzés megtörtént.');
  const downloadPromise = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Mentett feljegyzés', exact: true }).click();
  expect((await downloadPromise).suggestedFilename()).toMatch(/merfoldko\.txt$/);
  await dialog.getByRole('combobox', { name: 'Státusz', exact: true }).selectOption('completed');
  await dialog.getByRole('button', { name: 'Mérföldkő mentése', exact: true }).click();
  await expect(page.getByText('Nincs a szűrésnek megfelelő mérföldkő.')).toBeVisible();
  await page.getByLabel('Mérföldkövek szűrése', { exact: true }).selectOption('all');
  await expect(page.getByRole('region', { name: 'Mérföldkövek táblázata' })).toContainText('Teljesítve');
  if (testInfo.project.name === 'mobile') {
    await page.getByRole('button', { name: 'Navigáció megnyitása' }).click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await page.getByRole('button', { name: 'Navigáció bezárása' }).click();
  }
  await page.getByLabel('Projekt keresése', { exact: true }).fill('nincsilyenprojekt');
  await expect(page.getByRole('heading', { name: 'Nincs a szűrésnek megfelelő projekt' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
